def can_render_raw_command(command) -> bool:
    name = command["command"]
    args = list(command["args"])
    if name not in RAW_TRANSLATABLE_COMMANDS:
        return False
    if name == "gettrainername":
        return (
            len(args) >= 3
            and normalize_string_buffer_arg(args[0]) is not None
            and trainer_constant_name(args[1], args[2]) in CONSTANT_NAMES
        )
    if name == "jumpstd":
        return bool(args) and args[0] in STANDARD_GOTO_SCRIPTS
    if name == "special":
        return bool(args) and (args[0] in AVAILABLE_SPECIALS or args[0] in RAW_SPECIAL_TRANSLATIONS)
    return True


def render_raw_script_command(entry, ir, script_categories, command):
    name = command["command"]
    args = list(command["args"])
    rendered_name = RAW_COMMAND_ALIASES.get(name, name)

    if name == "readvar":
        translated_lines = RAW_READVAR_TRANSLATIONS.get(args[0]) if args else None
        if translated_lines is not None:
            return [f"\t{line}" for line in translated_lines]
    if name == "special":
        translated_lines = RAW_SPECIAL_TRANSLATIONS.get(args[0])
        if translated_lines is not None:
            return [f"\t{line}" for line in translated_lines]

    if name == "writetext":
        args = [generated_asset_label(entry, args[0])]
    elif name == "applymovement":
        args = [normalize_raw_object_arg(ir, args[0]), generated_asset_label(entry, args[1])]
    elif name == "turnobject":
        args = [normalize_raw_object_arg(ir, args[0]), CRYSTAL_TO_EMERALD_DIR.get(args[1], args[1])]
    elif name == "moveobject":
        args = [normalize_raw_object_arg(ir, args[0]), args[1], args[2]]
    elif name in {"appear", "disappear"}:
        args = [normalize_raw_object_arg(ir, args[0])]
    elif name in {"jump", "sjump", "call", "scall", "iftrue", "iffalse"}:
        args = [generated_script_label(entry, args[0])]
    elif name in {"ifequal", "ifnotequal", "ifgreater", "ifless"}:
        args = [normalize_raw_value_arg(args[0]), generated_script_label(entry, args[1])]
    elif name in {"giveitem", "verbosegiveitem", "checkitem", "takeitem"}:
        args = [normalize_item_constant(args[0]), *args[1:]]
    elif name == "cry":
        args = [normalize_species_constant(args[0])]
    elif name == "playmusic":
        args = [normalize_music_constant(args[0])]
    elif name == "playsound":
        args = [normalize_sound_constant(args[0])]
    elif name == "setval":
        args = [normalize_raw_value_arg(args[0])]
    elif name == "gettrainername":
        rendered_name = "buffertrainername"
        args = [normalize_string_buffer_arg(args[0]), trainer_constant_name(args[1], args[2])]
    elif name == "jumpstd":
        rendered_name = "goto"
        args = [STANDARD_GOTO_SCRIPTS[args[0]]]

    return f"\t{rendered_name}" if not args else f"\t{rendered_name} {', '.join(args)}"


def raw_script_plan(entry, ir, script_label: str, script_categories):
    reachable_labels = []
    reachable_set = set()
    stack = [script_label]

    while stack:
        current = stack.pop()
        if current in reachable_set:
            continue

        script = ir["scripts"].get(current)
        if script is None:
            return None
        if any(not can_render_raw_command(command) for command in script["commands"]):
            return None
        if not script["commands"]:
            return None
        if script["commands"][-1]["command"] not in RAW_TERMINATING_COMMANDS and script.get("fallthrough_label") is None:
            return None
        if any(not can_render_generated_text(ir, text_label) for text_label in script.get("text_refs", [])):
            return None
        if any(not can_render_generated_movement(ir, movement_label) for movement_label in script.get("movement_refs", [])):
            return None

        reachable_set.add(current)
        reachable_labels.append(current)
        for label_ref in script.get("label_refs", []):
            if label_ref in script_categories and label_ref != script_label:
                continue
            stack.append(label_ref)

    ordered_labels = []
    emitted = set()

    def emit_order(current):
        if current in emitted:
            return
        emitted.add(current)
        ordered_labels.append(current)
        for label_ref in ir["scripts"][current].get("label_refs", []):
            if label_ref in reachable_set:
                emit_order(label_ref)

    emit_order(script_label)

    lines = []
    for current in ordered_labels:
        lines.append(f"{generated_script_label(entry, current)}::")
        for command in ir["scripts"][current]["commands"]:
            rendered = render_raw_script_command(entry, ir, script_categories, command)
            if isinstance(rendered, list):
                lines.extend(rendered)
            else:
                lines.append(rendered)
        lines.append("")

    return lines


def compile_script_plan(entry, ir, script_label: str, category: str, script_categories):
    trainer_plan = trainer_script_plan(entry, ir, script_label)
    if trainer_plan is not None:
        return trainer_plan

    special_plan = special_script_plan(entry, ir, script_label)
    if special_plan is not None:
        if special_plan["type"] == "itemball":
            return [
                f"{generated_script_label(entry, script_label)}::",
                f"\tfinditem {special_plan['item']}",
                "\tend",
                "",
            ]
        if special_plan["type"] == "hiddenitem":
            return [
                f"{generated_script_label(entry, script_label)}::",
                f"\tsetorcopyvar VAR_0x8004, {special_plan['flag']}",
                f"\tsetorcopyvar VAR_0x8005, {special_plan['item']}",
                "\tgoto EventScript_HiddenItemScript",
                "",
            ]
        if special_plan["type"] == "pokecenter_nurse":
            return [
                f"{generated_script_label(entry, script_label)}::",
                f"\tsetorcopyvar VAR_0x800B, {special_plan['local_id']}",
                "\tcall Common_EventScript_PkmnCenterNurse",
                "\twaitmessage",
                "\twaitbuttonpress",
                "\trelease",
                "\tend",
                "",
            ]
        if special_plan["type"] == "pokemart":
            mart_label = mart_label_name(entry, script_label)
            lines = [
                f"{generated_script_label(entry, script_label)}::",
                "\tlock",
            ]
            if special_plan["needs_faceplayer"]:
                lines.append("\tfaceplayer")
            else:
                lines.append("\tfaceplayer")
            lines.extend(
                [
                    "\tmessage gText_HowMayIServeYou",
                    "\twaitmessage",
                    f"\tpokemart {mart_label}",
                    "\tmsgbox gText_PleaseComeAgain, MSGBOX_DEFAULT",
                    "\trelease",
                    "\tend",
                    "",
                    "\t.align 2",
                    f"{mart_label}:",
                ]
            )
            for item in special_plan["items"]:
                lines.append(f"\t.2byte {item}")
            lines.extend(
                [
                    "\tpokemartlistend",
                    "",
                ]
            )
            return lines
        if special_plan["type"] == "goto":
            return [
                f"{generated_script_label(entry, script_label)}::",
                f"\tgoto {special_plan['target']}",
                "",
            ]

    plan = simple_text_script_plan(entry, ir, script_label)
    if plan is not None:
        return render_simple_msgbox_script(
            entry,
            script_label,
            plan["text_label"],
            category,
            faceplayer=plan["needs_faceplayer"],
        )

    conditional_plan = conditional_text_script_plan(entry, ir, script_label)
    if conditional_plan is not None:
        branch_label = f"{generated_script_label(entry, script_label)}_Branch"
        msgbox_kind = "MSGBOX_SIGN" if category == "bg" else "MSGBOX_DEFAULT"
        goto_opcode = "goto_if_set" if conditional_plan["branch_on_true"] else "goto_if_unset"
        lines = [f"{generated_script_label(entry, script_label)}::"]
        if category == "object":
            lines.append("\tlock")
            if conditional_plan["needs_faceplayer"]:
                lines.append("\tfaceplayer")
        lines.append(f"\t{goto_opcode} {conditional_plan['check_target']}, {branch_label}")
        lines.append(f"\tmsgbox {generated_asset_label(entry, conditional_plan['main_text_label'])}, {msgbox_kind}")
        if category == "object":
            lines.append("\trelease")
        lines.append("\tend")
        lines.append("")
        lines.append(f"{branch_label}:")
        lines.append(f"\tmsgbox {generated_asset_label(entry, conditional_plan['branch_text_label'])}, {msgbox_kind}")
        if category == "object":
            lines.append("\trelease")
        lines.append("\tend")
        lines.append("")
        return lines

    raw_plan = raw_script_plan(entry, ir, script_label, script_categories)
    if raw_plan is not None:
        return raw_plan

    return None


def collect_event_script_categories(ir):
    categories = {}

    def register(script_label: str, category: str):
        if SCRIPT_CATEGORY_PRIORITY.get(category, 0) > SCRIPT_CATEGORY_PRIORITY.get(categories.get(script_label, ""), 0):
            categories[script_label] = category

    for event in ir["events"]["object_events"]:
        register(event["script"], "object")
    for event in ir["events"]["coord_events"]:
        register(event["script"], "coord")
    for event in ir["events"]["bg_events"]:
        register(event["script"], "bg")
    return categories


def append_unique_script_blocks(lines, compiled_lines, emitted_labels):
    block_lines = []
    block_label = None

    def flush():
        nonlocal block_lines, block_label
        if not block_lines:
            return
        if block_label is None or block_label not in emitted_labels:
            if block_label is not None:
                emitted_labels.add(block_label)
            lines.extend(block_lines)
        block_lines = []
        block_label = None

    for line in compiled_lines:
        stripped = line.strip()
        if stripped.endswith("::"):
            flush()
            block_label = stripped[:-2]
            block_lines = [line]
            continue
        if stripped.endswith(":") and stripped[:-1]:
            flush()
            block_label = stripped[:-1]
            block_lines = [line]
            continue
        block_lines.append(line)

    flush()


def build_generated_scripts(entry, ir) -> str:
    placeholder_text = event_placeholder_text_label(entry)
    script_categories = collect_event_script_categories(ir)
    emitted_labels = set()
    lines = [
        AUTO_SCRIPT_HEADER,
        "",
        f"{entry['target_name']}_MapScripts::",
        "\t.byte 0",
        "",
        f"{placeholder_text}:",
        '\t.string "This part of Johto is still being restored.$"',
        "",
    ]

    for script_label in sorted(script_categories):
        category = script_categories[script_label]
        compiled_lines = compile_script_plan(entry, ir, script_label, category, script_categories)
        if compiled_lines is not None:
            append_unique_script_blocks(lines, compiled_lines, emitted_labels)
            continue

        lines.append(f"{generated_script_label(entry, script_label)}::")
        if category == "object":
            lines.append("\tlock")
            lines.append("\tfaceplayer")
            lines.append(f"\tmsgbox {placeholder_text}, MSGBOX_DEFAULT")
            lines.append("\trelease")
        else:
            msgbox_kind = "MSGBOX_SIGN" if category == "bg" else "MSGBOX_DEFAULT"
            lines.append(f"\tmsgbox {placeholder_text}, {msgbox_kind}")
        lines.append("\tend")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def write_generated_script_assets(manifest, ir_index):
    global_text_assets = {}
    global_movement_assets = {}
    for entry in manifest:
        ir = ir_index[entry["crystal_map"]]
        for label, text_block in ir["texts"].items():
            global_text_assets.setdefault(label, text_block)
        for label, script_block in ir["scripts"].items():
            if label not in global_text_assets and text_block_like(script_block):
                global_text_assets[label] = script_block
        for label, movement_block in ir["movements"].items():
            global_movement_assets.setdefault(label, movement_block)

    lines = [
        "@ Generated by scripts/import_johto_maps.py. Do not edit manually.",
        "@ Crystal-authored text and movement assets for imported Johto maps.",
        "",
    ]

    for entry in manifest:
        ir = ir_index[entry["crystal_map"]]
        if not ir["texts"] and not ir["movements"]:
            continue

        lines.append(f"@ {entry['target_name']} <= {entry['crystal_map']}")
        numeric_constants = load_text_numeric_constants(ir)

        text_assets = dict(ir["texts"])
        for label, script_block in ir["scripts"].items():
            if label not in text_assets and text_block_like(script_block):
                text_assets[label] = script_block
        for script_block in ir["scripts"].values():
            text_labels = set(script_block.get("text_refs", []))
            text_labels.update(script_text_command_refs(script_block))
            for text_label in text_labels:
                if text_label not in text_assets and text_label in global_text_assets:
                    text_assets[text_label] = global_text_assets[text_label]

        for label, text_block in text_assets.items():
            fragments, unsupported = convert_text_block(text_block, numeric_constants)
            if unsupported or fragments is None:
                detail = ", ".join(unsupported)
                if not detail:
                    detail = "empty rendered text"
                lines.append(f"@ skipped text asset {label}: unsupported commands {detail}")
                continue

            lines.append(f"{generated_asset_label(entry, label)}:")
            for fragment in fragments:
                lines.append(f'\t.string "{escape_emerald_string(fragment)}"')
            lines.append("")

        movement_assets = dict(ir["movements"])
        for script_block in ir["scripts"].values():
            movement_labels = set(script_block.get("movement_refs", []))
            movement_labels.update(script_movement_command_refs(script_block))
            for movement_label in movement_labels:
                if movement_label not in movement_assets and movement_label in global_movement_assets:
                    movement_assets[movement_label] = global_movement_assets[movement_label]

        for label, movement_block in movement_assets.items():
            movement_lines, unsupported = convert_movement_block(movement_block)
            if unsupported:
                detail = ", ".join(unsupported)
                lines.append(f"@ skipped movement asset {label}: unsupported commands {detail}")
                continue

            lines.append(f"{generated_asset_label(entry, label)}:")
            for movement_line in movement_lines:
                lines.append(f"\t{movement_line}")
            lines.append("")

    GENERATED_JOHTO_ASSETS_PATH.write_text("\n".join(lines).rstrip() + "\n")
    print(f"updated {GENERATED_JOHTO_ASSETS_PATH.relative_to(ROOT)}")


