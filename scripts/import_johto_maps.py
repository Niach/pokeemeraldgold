def load_crystal_marts():
    mart_constants = []
    for raw_line in CRYSTAL_MART_CONSTANTS_PATH.read_text().splitlines():
        line = raw_line.split(";", 1)[0].strip()
        match = MART_CONST_RE.match(line)
        if match is not None:
            mart_constants.append(match.group(1))

    mart_labels = []
    in_table = False
    for raw_line in CRYSTAL_MARTS_PATH.read_text().splitlines():
        line = raw_line.split(";", 1)[0].strip()
        if line == "Marts:":
            in_table = True
            continue
        if not in_table:
            continue
        if line.startswith("assert_table_length"):
            break
        match = MART_POINTER_RE.match(line)
        if match is not None:
            mart_labels.append(match.group(1))

    if len(mart_constants) != len(mart_labels):
        raise RuntimeError(f"mart constant/table mismatch: {len(mart_constants)} constants vs {len(mart_labels)} labels")

    label_to_items = {}
    current_label = None
    skip_count = False
    for raw_line in CRYSTAL_MARTS_PATH.read_text().splitlines():
        line = raw_line.split(";", 1)[0].strip()
        if not line:
            continue
        if line.endswith(":"):
            current_label = line[:-1]
            if current_label in mart_labels:
                label_to_items[current_label] = []
                skip_count = True
            else:
                current_label = None
            continue
        if current_label is None:
            continue
        match = MART_ITEM_RE.match(line)
        if match is None:
            continue
        token = match.group(1)
        if skip_count:
            skip_count = False
            continue
        if token == "-1":
            current_label = None
            continue
        label_to_items[current_label].append(normalize_item_constant(token))

    marts = {}
    for mart_constant, mart_label in zip(mart_constants, mart_labels):
        marts[mart_constant] = label_to_items.get(mart_label, [])
    return marts


