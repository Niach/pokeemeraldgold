def simple_text_body(script):
    if script is None:
        return None

    commands = script["commands"]
    index = 0

    if index < len(commands) and commands[index]["command"] == "endifjustbattled":
        index += 1
    if index < len(commands) and commands[index]["command"] == "opentext":
        index += 1
    if index >= len(commands) or commands[index]["command"] != "writetext" or not commands[index]["args"]:
        return None

    text_label = commands[index]["args"][0]
    index += 1
    while index < len(commands) and commands[index]["command"] in {"waitbutton", "promptbutton"}:
        index += 1
    if index >= len(commands) or commands[index]["command"] != "closetext":
        return None
    index += 1
    if index >= len(commands) or commands[index]["command"] != "end":
        return None
    index += 1
    if index != len(commands):
        return None

    return text_label


