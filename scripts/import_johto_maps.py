def stamp_johto_berry_soil(metatile_rows, map_data):
    height = len(metatile_rows)
    width = len(metatile_rows[0]) if height else 0

    for event in map_data.get("object_events", []):
        berry_tree = event.get("trainer_sight_or_berry_tree_id")
        if event.get("movement_type") != "MOVEMENT_TYPE_BERRY_TREE_GROWTH":
            continue
        if berry_tree not in JOHTO_BERRY_TREES_BY_CONSTANT:
            continue
        if not JOHTO_BERRY_TREES_BY_CONSTANT[berry_tree]["needs_soil"]:
            continue

        x = int(event["x"])
        y = int(event["y"])
        if not (0 <= x < width and 0 <= y < height):
            raise ValueError(f"{map_data['name']}: berry soil position {(x, y)} is out of bounds")

        metatile_rows[y][x] = berry_soil_mapgrid_entry(int(event.get("elevation", 3)))


def apply_text_substitutions(value: str) -> str:
    for source, target in TEXT_SUBSTITUTIONS:
        value = value.replace(source, target)
    # Crystal uses "#" as a POKe prefix marker in many compounds
    # (for example "# BALL", "#MANIAC", "# SEER"), and "@" as an
    # inline join marker around text_ram/text_start boundaries.
    value = value.replace("#", "POKé")
    value = value.replace("@", "")
    return value


def escape_emerald_string(value: str) -> str:
    return value.replace('"', '\\"')


def load_text_numeric_constants(ir):
    source_asm = ir.get("source_asm")
    cached = TEXT_NUMERIC_CONSTANTS_CACHE.get(source_asm)
    if cached is not None:
        return cached

    constants = dict(GLOBAL_TEXT_NUMERIC_CONSTANTS)
    if source_asm:
        source_path = CRYSTAL_ROOT / source_asm
        if source_path.exists():
            for raw_line in source_path.read_text().splitlines():
                line = raw_line.split(";", 1)[0].strip()
                match = LOCAL_TEXT_CONSTANT_RE.match(line)
                if match is None:
                    continue
                constants.setdefault(match.group(1), match.group(2))

    TEXT_NUMERIC_CONSTANTS_CACHE[source_asm] = constants
    return constants


def resolve_decimal_text_placeholders(value: str, numeric_constants):
    unresolved = []

    def replacer(match):
        constant_name = match.group(1)
        replacement = numeric_constants.get(constant_name)
        if replacement is None:
            unresolved.append(f"decimal {constant_name}")
            return match.group(0)
        return replacement

    return DECIMAL_TEXT_PLACEHOLDER_RE.sub(replacer, value), unresolved


