def text_block_like(block):
    commands = block.get("commands", [])
    return bool(commands) and all(command.get("command") in TEXT_COMMAND_NAMES for command in commands)


def get_text_block(ir, text_label: str):
    text_block = ir["texts"].get(text_label)
    if text_block is not None:
        return text_block

    script_block = ir["scripts"].get(text_label)
