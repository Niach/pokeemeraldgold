def load_tmhm_item_maps():
    tm_map = {}
    hm_map = {}
    mode = None
    tm_index = 1
    hm_index = 1
    for raw_line in (ROOT / "include" / "constants" / "tms_hms.h").read_text().splitlines():
        line = raw_line.strip()
        if line.startswith("#define FOREACH_TM("):
            mode = "tm"
            continue
        if line.startswith("#define FOREACH_HM("):
            mode = "hm"
            continue
        if line.startswith("#define FOREACH_TMHM("):
            mode = None
            continue

        match = TMHM_LINE_RE.search(line)
        if match is None or mode is None:
            continue

        move_name = match.group(1)
        if mode == "tm":
            tm_map[move_name] = f"ITEM_TM{tm_index:02d}"
            tm_index += 1
        else:
            hm_map[move_name] = f"ITEM_HM{hm_index:02d}"
            hm_index += 1

    return tm_map, hm_map


