def simple_text_script_plan(entry, ir, script_label: str):
    script = ir["scripts"].get(script_label)
    if script is None:
        return None
    commands = script["commands"]
    command_names = [command["command"] for command in commands]

    if command_names == ["jumptext"] and commands[0]["args"]:
        return {
            "type": "simple_text",
            "text_label": commands[0]["args"][0],
            "needs_faceplayer": False,
        }

    if command_names == ["jumptextfaceplayer"] and commands[0]["args"]:
        return {
            "type": "simple_text",
            "text_label": commands[0]["args"][0],
            "needs_faceplayer": True,
        }

    needs_faceplayer = False
    if commands and commands[0]["command"] == "faceplayer":
        needs_faceplayer = True
        commands = commands[1:]

    text_label = simple_text_body({"commands": commands})
    if text_label is None:
        return None

    text_block = get_text_block(ir, text_label)
    if text_block is None:
        return None

    fragments, unsupported = convert_text_block(text_block, load_text_numeric_constants(ir))
    if unsupported:
        return None

    return {
        "type": "simple_text",
        "text_label": text_label,
        "needs_faceplayer": needs_faceplayer,
    }


def conditional_text_script_plan(entry, ir, script_label: str):
    script = ir["scripts"].get(script_label)
    if script is None:
        return None

    commands = script["commands"]
    index = 0
    needs_faceplayer = False
    if index < len(commands) and commands[index]["command"] == "faceplayer":
        needs_faceplayer = True
        index += 1
    if index >= len(commands) or commands[index]["command"] != "opentext":
        return None
    index += 1
    if index + 5 >= len(commands):
        return None

    check_command = commands[index]
    branch_command = commands[index + 1]
    text_command = commands[index + 2]
    if check_command["command"] not in {"checkevent", "checkflag"} or not check_command["args"]:
        return None
    if check_command["args"][0] not in CONSTANT_NAMES:
        return None
    if branch_command["command"] not in {"iftrue", "iffalse"} or not branch_command["args"]:
        return None
    if text_command["command"] != "writetext" or not text_command["args"]:
        return None
    if commands[index + 3]["command"] not in {"waitbutton", "promptbutton"}:
        return None
    if commands[index + 4]["command"] != "closetext" or commands[index + 5]["command"] != "end":
        return None
    if index + 6 != len(commands):
        return None

    branch_label = branch_command["args"][0]
    branch_text_label = simple_text_body(ir["scripts"].get(branch_label))
    if branch_text_label is None:
        return None

    main_text_block = get_text_block(ir, text_command["args"][0])
    branch_text_block = get_text_block(ir, branch_text_label)
    if main_text_block is None or branch_text_block is None:
        return None

    main_fragments, main_unsupported = convert_text_block(main_text_block, load_text_numeric_constants(ir))
    branch_fragments, branch_unsupported = convert_text_block(branch_text_block, load_text_numeric_constants(ir))
    if main_unsupported or branch_unsupported:
        return None

    return {
        "type": "conditional_text",
        "check_kind": check_command["command"],
        "check_target": check_command["args"][0],
        "branch_on_true": branch_command["command"] == "iftrue",
        "main_text_label": text_command["args"][0],
        "branch_text_label": branch_text_label,
        "needs_faceplayer": needs_faceplayer,
    }


