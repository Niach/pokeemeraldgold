def trainer_script_plan(entry, ir, script_label: str):
    script = ir["scripts"].get(script_label)
    if script is None or not script["commands"] or script["commands"][0]["command"] != "trainer":
        return None

    args = script["commands"][0]["args"]
    if len(args) < 5:
        return None

    trainer_class, trainer_name = args[0], args[1]
    seen_text_label, beaten_text_label = args[3], args[4]
    if not text_label_is_supported(ir, seen_text_label) or not text_label_is_supported(ir, beaten_text_label):
        return None

    followup_text_label = trainer_followup_text_label(script["commands"][1:])
    if followup_text_label is None and len(args) >= 7 and args[6] != "0":
        followup_script = ir["scripts"].get(args[6])
        if followup_script is not None:
            followup_text_label = trainer_followup_text_label(followup_script["commands"])
    if followup_text_label is not None and not text_label_is_supported(ir, followup_text_label):
        followup_text_label = None

    trainer_constant = trainer_constant_name(trainer_class, trainer_name)
    lines = [f"{generated_script_label(entry, script_label)}::"]

    if followup_text_label is None:
        lines.append(
            f"\ttrainerbattle_single {trainer_constant}, "
            f"{generated_asset_label(entry, seen_text_label)}, "
            f"{generated_asset_label(entry, beaten_text_label)}"
        )
        lines.append("")
        return lines

    callback_label = f"{generated_script_label(entry, script_label)}_AfterBattle"
    lines.append(
        f"\ttrainerbattle_single {trainer_constant}, "
        f"{generated_asset_label(entry, seen_text_label)}, "
        f"{generated_asset_label(entry, beaten_text_label)}, "
        f"{callback_label}"
    )
    lines.extend(
        [
            "",
            f"{callback_label}::",
            f"\tmsgbox {generated_asset_label(entry, followup_text_label)}, MSGBOX_DEFAULT",
            "\tend",
            "",
        ]
    )
    return lines


