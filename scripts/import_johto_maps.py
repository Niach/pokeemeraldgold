def load_define_names(path):
    names = set()
    if not path.exists():
        return names

    for raw_line in path.read_text().splitlines():
        line = raw_line.split("//", 1)[0].strip()
        match = C_DEFINE_RE.match(line)
        if match is not None:
            names.add(match.group(1))
    return names


def load_constant_names_from_dir(directory):
    names = set()
    if not directory.exists():
        return names
    for path in directory.rglob("*.h"):
        names.update(load_define_names(path))
    return names


